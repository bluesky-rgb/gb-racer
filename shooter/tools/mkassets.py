class Packer:
    def __init__(self):
        self.cells, self.index = [], {}
    @staticmethod
    def _flip(d): return bytes(int(f"{b:08b}"[::-1], 2) for b in d)
    def add(self, cv, attr=0):
        pieces = []
        for cy in range(0, cv.h, 16):
            for cx in range(0, cv.w, 8):
                if all(cv.px[cy + j][cx + i] is None for j in range(16) for i in range(8)): continue
                d = tile_bytes(cv.px, cx, cy) + tile_bytes(cv.px, cx, cy + 8)
                a = attr
                if d in self.index: idx = self.index[d]
                elif self._flip(d) in self.index: idx = self.index[self._flip(d)]; a ^= 0x20
                else: idx = len(self.cells); self.cells.append(d); self.index[d] = idx
                pieces.append((cy, cx, idx * 2, a))
        return pieces

