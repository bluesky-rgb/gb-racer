def starfield(seed, density=0.16):
    rnd = random.Random(seed)
    c = Canvas(256, 256, 2)
    variants = [[(3, 3, 0)], [(5, 2, 1)], [(2, 6, 1)], [(4, 4, 0), (3, 4, 1), (5, 4, 1), (4, 3, 1), (4, 5, 1)],
                [(6, 6, 1)], [(1, 1, 1), (6, 5, 0)]]
    for ty in range(32):
        for tx in range(32):
            if rnd.random() < density:
                for (x, y, col) in rnd.choice(variants): c.px[ty * 8 + y][tx * 8 + x] = col
    return c

def planet(c, cx, cy, r, ring=True):
    for y in range(int(cy - r - 2), int(cy + r + 3)):
        for x in range(int(cx - r - 2), int(cx + r + 3)):
            d = math.hypot(x - cx, y - cy)
            if d <= r:
                light = (x - cx) * -0.6 + (y - cy) * -0.5           # lit from the top left
                col = 0 if light > r * 0.55 else 1 if light > -r * 0.15 else 3 if light < -r * 0.6 else 2
                if col == 1 and (int(y - cy + r) // 5) % 2 == 0 and ((x + y) & 1): col = 0 if light > r * 0.2 else 1
                if col == 2 and ((x + y) & 1): col = 3
                c.set(x, y, col)
    if ring:
        for t in range(0, 720):
            a = t * math.pi / 360
            for k in (0, 1, 2):
                x = cx + (r * 1.75 + k) * math.cos(a); y = cy + (r * 0.42 + k * 0.3) * math.sin(a)
                behind = math.sin(a) < 0 and math.hypot(x - cx, y - cy) < r
                if not behind: c.set(int(round(x)), int(round(y)), 0 if k == 1 else 1)

def rock(c, cx, cy, r, seed):
    rnd = random.Random(seed)
    pts = [(cx + r * (0.7 + 0.3 * rnd.random()) * math.cos(a), cy + r * (0.7 + 0.3 * rnd.random()) * math.sin(a))
           for a in [i * 2 * math.pi / 9 for i in range(9)]]
    c.poly(pts, 1)
    for y in range(int(cy - r), int(cy + r) + 1):
        for x in range(int(cx - r), int(cx + r) + 1):
            if c.get(x, y) == 1:
                s = (x - cx) * 0.7 + (y - cy) * 0.7
                if s > r * 0.35: c.set(x, y, 3)
                elif s > 0 and (x + y) & 1: c.set(x, y, 2)
                elif s < -r * 0.5: c.set(x, y, 0)
    for _ in range(2):
        a, d = rnd.random() * 6.28, rnd.random() * r * 0.4
        c.ellipse(cx + d * math.cos(a), cy + d * math.sin(a), max(1.2, r * 0.18), max(1.2, r * 0.15), 2)

