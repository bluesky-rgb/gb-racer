def glyph_pixels(ch, ink=0, paper=3):
    px = [[paper] * 8 for _ in range(8)]
    if ch in SPECIAL:
        for y, row in enumerate(SPECIAL[ch]):
            for x, c in enumerate(row):
                if c == 'X': px[y][x] = ink
    else:
        for y, row in enumerate(GLYPHS[ch].split()):
            for x, c in enumerate(row):
                if c == '#': px[y + 1][x + 1] = ink
    return px
