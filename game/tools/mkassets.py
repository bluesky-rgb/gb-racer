"""Build all graphics binaries + build/assets.inc from the procedural art in this directory."""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from gbgfx import Canvas, TileSet, tile_bytes
from geom import ROWS, SKY_ROWS
import font, mkroad
try:
    import art
except ImportError:
    art = None

OUT = sys.argv[1] if len(sys.argv) > 1 else "build"
inc = ["; generated by tools/mkassets.py - do not edit"]
BG_SKIP = (art.OBJ_TILE_LIMIT - 128) if art else 0

# ---- font: BG tiles 0..N-1, shared by every scene ----
font_tiles = b"".join(tile_bytes(font.glyph_pixels(ch), 0, 0) for ch in font.ORDER)
FONT_N = len(font.ORDER)
open(f"{OUT}/font.bin", "wb").write(font_tiles)
inc.append(f"DEF FONT_TILES EQU {FONT_N}")
cm = ["; generated - HUD font character map", "NEWCHARMAP hud"]
for i, ch in enumerate(font.ORDER):
    esc = {'"': '\\"', "\\": "\\\\"}.get(ch, ch)
    cm.append(f'CHARMAP "{esc}", {i}')
open(f"{OUT}/charmap.inc", "w").write("\n".join(cm) + "\n")

# ---- scenes: sky picture (256x80) + two road textures -> BG tiles + 32x28 map ----
def placeholder_sky(theme):
    c = Canvas(256, SKY_ROWS, 0)
    for x in range(256):
        for y in range(SKY_ROWS - 6, SKY_ROWS): c.px[y][x] = 1
    return c

for theme in mkroad.THEMES:
    sky = art.sky(theme) if art else placeholder_sky(theme)
    road = mkroad.road_canvas(theme)
    full = Canvas(256, SKY_ROWS + ROWS * 2)
    full.blit(sky, 0, 0)
    full.blit(road, 0, SKY_ROWS)
    ts = TileSet(base=FONT_N)
    ids = ts.add_image(full)
    # sprites borrow BG tile indices 128..(128+skip-1) on race screens
    skip = (art.TITLE_OBJ_LIMIT - 128 if art else 0) if theme == "title" else BG_SKIP
    assert FONT_N + len(ts) <= 256 - skip, f"{theme}: {FONT_N + len(ts)} BG tiles, room for {256 - skip}"
    ids = [i if i < 128 else i + skip for i in ids]
    open(f"{OUT}/bg_{theme}.bin", "wb").write(ts.data())
    open(f"{OUT}/map_{theme}.bin", "wb").write(bytes(ids))
    full.image(2).save(f"{OUT}/bg_{theme}.png")
    inc.append(f"DEF BG_{theme.upper()}_TILES EQU {len(ts)}")
    inc.append(f"DEF BG_{theme.upper()}_SKIP EQU {skip}")
    print(f"{theme}: {len(ts)} scene tiles (+{FONT_N} font) of {256 - skip}")

# ---- sprites ----
if art:
    art.build_sprites(OUT, inc)

open(f"{OUT}/assets.inc", "w").write("\n".join(inc) + "\n")
