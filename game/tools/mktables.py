"""Generate lookup tables (build/tables.asm) for the road renderer."""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from geom import *

out = []
def db(label, vals, per=16, comment=""):
    if label: out.append(f"{label}:: {('; ' + comment) if comment else ''}")
    for i in range(0, len(vals), per):
        out.append("    db " + ",".join(f"${v & 0xFF:02X}" for v in vals[i:i + per]))

out.append("; generated by tools/mktables.py - do not edit")
out.append('SECTION "StripeTables", ROMX[$4000], BANK[1]')
out.append("; StripeTab + phase*128 + row = BG source line (minus 1) for that row at that stripe phase")
z8 = [int((z_of(r) % 1.0) * 256) & 0xFF for r in range(ROWS)]
out.append("StripeTab::")
for p in range(64):
    phase = p * 4
    vals = []
    for r in range(ROWS):
        v = ((z8[r] + phase) & 0x80) >> 7
        # near the horizon one row spans most of a stripe period: sampling it would
        # flicker at random, so those rows keep the light variant
        if ZK / ((r + 1) * (r + 2)) > 0.45: v = 0
        vals.append(SKY_ROWS + ROWS * v + r - 1)
    vals += [0] * (128 - ROWS)
    db(None, vals, 32)

# hill maps: one 256-byte page per pitch. [0..71] = inverse map, the line map is
# right-aligned so that it ends on the page boundary (the copy loop ends on INC E overflow).
out.append('SECTION "HillMaps", ROMX[$6000], BANK[1]')
out.append("HillPages::")
starts, horizons = [], []
for p in range(-PITCH_MAX, PITCH_MAX + 1):
    rows, inv = hill_map(p)
    n = len(rows)
    assert ROWS + n <= 256
    page = inv + [0] * (256 - ROWS - n) + rows
    db(None, page, 32)
    starts.append(256 - n)
    horizons.append(ROAD_BOTTOM + 1 - n)

out.append('SECTION "RoadTables", ROMX, BANK[1]')
db("HillMapStart", starts, 17, "low byte where each pitch's line map starts")
db("HillHorizon", horizons, 17, "first road screen line for each pitch")
db("RoadHalfW", [int(round(half_width(r))) for r in range(ROWS)], 18)
# distance -> row. near table: index = distance * 8 (eighths of a period), far: whole periods
near = [max(0, row_of(i / 8.0)) if i > 0 else 127 for i in range(256)]
far = [row_of(float(i)) if i >= 32 else 0 for i in range(128)]
db("RowFar", [f & 0xFF for f in far], 16, "row for distance d periods, d >= 32 ($FF: beyond the horizon)")

def lvl(r, bounds):
    for i, b in enumerate(bounds):
        if r >= b: return i
    return len(bounds)

# page-aligned tables for the sprite placement code (fixed bank: always addressable)
out.append('SECTION "AlignedTables", ROM0, ALIGN[8]')
db("RowNear", near, 16, "row for distance d/8 periods (>=72: closer than the bottom row)")
obj = [lvl(r, [36, 26, 18, 12, 8, 5, 2]) for r in range(ROWS)]
car = [lvl(r, [56, 42, 28, 20, 12, 4]) for r in range(ROWS)]
db("LevelTab", obj + [7] * (128 - ROWS) + car + [6] * (128 - ROWS), 16,
   "[row] scenery size level (7 = none), [128+row] rival car size level (6 = none)")
# lateral offset in pixels of a point k eighths of the half-width from the road centre:
# LatTab + (k-1)*128 + row
out.append("LatTab::")
for k in range(1, 13):
    db(None, [int(round(k * half_width(r) / 8)) for r in range(ROWS)] + [0] * (128 - ROWS), 32)

open(sys.argv[1], "w").write("\n".join(out) + "\n")
print("tables:", "horizons", horizons)
