"""Stage scripts for ORBIT LANCE -> build/stages.asm.

Event: db wait (frames since the previous event), cmd, a, b, c
  cmd 1-3   spawn enemy (1 dart, 2 saucer, 3 heavy): a = x, b = pattern, c = parameter
  cmd 6     spawn power capsule at x = a
  cmd $F0   boss
  cmd $F1   banner (a = text number)
  cmd $F2   wait until the screen is clear
  cmd $FF   end of stage
Patterns: 0 straight (c = speed, 1/16 px), 1 weave (c = speed), 2 dive, 3 sweep from the left
(c = height), 4 sweep from the right, 5 hover (c = stop height)."""
import sys

DART, SAUCER, HEAVY = 1, 2, 3
STRAIGHT, WEAVE, DIVE, SWEEP_L, SWEEP_R, HOVER = range(6)
LEFT, MID, RIGHT = 32, 80, 128

class Script:
    def __init__(self):
        self.ev, self.t, self.last = [], 0, 0
    def at(self, dt):
        self.t += dt; return self
    def put(self, cmd, a=0, b=0, c=0):
        wait = self.t - self.last
        while wait > 255:                       # long gaps become empty waits
            self.ev.append((255, 0, 0, 0, 0)); wait -= 255
        self.ev.append((wait, cmd, a, b, c)); self.last = self.t
    def line(self, kind, xs, pat, prm, gap=0):
        for i, x in enumerate(xs):
            if i: self.at(gap)
            self.put(kind, x, pat, prm)
        return self
    def train(self, kind, x, pat, prm, n, gap):
        return self.line(kind, [x] * n, pat, prm, gap)

def stage(n):
    s = Script()
    s.at(150)                                   # stage banner
    if n == 0:
        s.train(DART, MID, STRAIGHT, 24, 5, 14).at(70)
        s.line(DART, [LEFT, 56, 104, RIGHT], STRAIGHT, 22, 10).at(80)
        s.train(SAUCER, 48, WEAVE, 10, 4, 24).at(30)
        s.train(SAUCER, 112, WEAVE, 10, 4, 24).at(90)
        s.train(DART, 0, SWEEP_L, 36, 6, 10).at(60)
        s.put(6, MID); s.at(60)
        s.train(DART, 168, SWEEP_R, 52, 6, 10).at(80)
        s.put(HEAVY, MID, HOVER, 52); s.at(40)
        s.line(DART, [LEFT, RIGHT, LEFT, RIGHT], DIVE, 0, 24).at(150)
        s.line(SAUCER, [24, 56, 104, 136], WEAVE, 12, 8).at(90)
        s.train(DART, 0, SWEEP_L, 30, 5, 10).at(6)
        s.train(DART, 168, SWEEP_R, 60, 5, 10).at(80)
        s.put(HEAVY, 48, HOVER, 44); s.at(30); s.put(HEAVY, 112, HOVER, 60); s.at(200)
        s.put(6, 48); s.at(120)
    elif n == 1:
        s.line(DART, [24, 48, 72, 96, 120, 144], STRAIGHT, 28, 6).at(70)
        s.line(DART, [144, 120, 96, 72, 48, 24], STRAIGHT, 28, 6).at(80)
        s.put(HEAVY, 40, HOVER, 50); s.at(20); s.put(HEAVY, 120, HOVER, 50); s.at(60)
        s.train(SAUCER, MID, WEAVE, 12, 5, 20).at(80)
        s.put(6, 112); s.at(30)
        s.line(DART, [LEFT, MID, RIGHT, 56, 104], DIVE, 0, 18).at(90)
        s.train(DART, 0, SWEEP_L, 40, 6, 9).at(10)
        s.train(DART, 168, SWEEP_R, 40, 6, 9).at(90)
        s.put(HEAVY, MID, HOVER, 40); s.at(10)
        s.train(SAUCER, 32, WEAVE, 14, 3, 24).at(10)
        s.train(SAUCER, 128, WEAVE, 14, 3, 24).at(140)
        s.line(DART, [MID, 56, 104, LEFT, RIGHT, MID], DIVE, 0, 14).at(120)
        s.put(6, MID); s.at(120)
    else:
        s.train(SAUCER, 64, WEAVE, 14, 6, 16).at(40)
        s.train(SAUCER, 96, WEAVE, 14, 6, 16).at(60)
        s.put(HEAVY, 48, HOVER, 40); s.at(0); s.put(HEAVY, 112, HOVER, 40); s.at(90)
        s.line(DART, [40, 60, 80, 100, 120], STRAIGHT, 34, 4).at(40)
        s.line(DART, [50, 70, 90, 110], STRAIGHT, 34, 4).at(80)
        s.put(6, MID); s.at(20)
        s.train(DART, 0, SWEEP_L, 30, 8, 8).at(10)
        s.train(DART, 168, SWEEP_R, 56, 8, 8).at(80)
        s.line(DART, [LEFT, RIGHT, MID, LEFT, RIGHT, MID, 56, 104], DIVE, 0, 12).at(80)
        s.put(HEAVY, MID, HOVER, 60); s.at(20)
        s.train(SAUCER, 40, WEAVE, 16, 4, 20).at(0)
        s.train(SAUCER, 120, WEAVE, 16, 4, 20).at(200)
        s.put(6, MID); s.at(120)
    s.put(0xF2); s.at(30)
    s.put(0xF1, 0); s.at(150)                   # WARNING
    s.put(0xF0); s.at(10)
    s.put(0xF2); s.at(1)
    s.put(0xFF)
    return s

out = ["; generated by tools/mkstages.py - do not edit", 'SECTION "Stages", ROM0', "StageTable::",
       "    dw Stage0, Stage1, Stage2"]
for n in range(3):
    s = stage(n)
    out.append(f"Stage{n}:")
    for e in s.ev: out.append("    db " + ", ".join(str(v) for v in e))
    print(f"stage {n + 1}: {len(s.ev)} events, {s.t / 60:.0f} s before the boss")
import math
out.append('SECTION "SinTab", ROM0, ALIGN[8]')
out.append("SinTab:: ; 256 steps per turn, amplitude 28")
vals = [int(round(28 * math.sin(i * 2 * math.pi / 256))) & 0xFF for i in range(256)]
for i in range(0, 256, 32): out.append("    db " + ",".join(f"${v:02X}" for v in vals[i:i + 32]))
open(sys.argv[1], "w").write("\n".join(out) + "\n")
