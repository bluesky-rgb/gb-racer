def stage3():
    c = starfield(33, 0.12)
    def wall(x0, x1, face_right):
        for y in range(256):
            for x in range(x0, x1):
                c.px[y][x] = 1
            edge = x1 - 1 if face_right else x0
            c.px[y][edge] = 3
            c.px[y][edge + (-1 if face_right else 1)] = 2
        for py in range(0, 256, 32):                 # panels
            for x in range(x0, x1): c.px[py][x] = 3
            for x in range(x0, x1): c.px[(py + 1) % 256][x] = 0
            for (rx, ry) in ((x0 + 3, py + 4), (x1 - 5, py + 4), (x0 + 3, py + 27), (x1 - 5, py + 27)):
                c.rect(rx, ry, rx + 1, ry + 1, 2)
            if (py // 32) % 2 == 0:                  # vents
                for k in range(3):
                    c.rect(x0 + 6, py + 10 + k * 5, x1 - 8, py + 11 + k * 5, 3)
            else:                                    # pipe
                px0 = x0 + 10
                c.rect(px0, py + 2, px0 + 6, py + 31, 2)
                c.rect(px0 + 1, py + 2, px0 + 2, py + 31, 0)
                c.rect(px0 - 1, py + 14, px0 + 7, py + 17, 3)
            ly = py + 20                             # warning light
            lx = x1 - 6 if face_right else x0 + 4
            c.rect(lx, ly, lx + 1, ly + 1, 0)
    wall(0, 32, True)
    wall(128, 160, False)
    for x in range(160, 256):
        for y in range(256): c.px[y][x] = 1
    return c

def title():
    c = starfield(44, 0.1)
    def word(text, y0, s, x_shift=0):
        pitch = 6 * s
        x0 = 80 - (len(text) * pitch - s) // 2 + x_shift
        cells = []
        for k, ch in enumerate(text):
            for y, row in enumerate(font.GLYPHS[ch].split()):
                for x, v in enumerate(row):
                    if v == '#': cells.append((x0 + k * pitch + x * s, y0 + y * s))
        for (px, py) in cells: c.rect(px - 1, py - 1, px + s, py + s, 3)
        for (px, py) in cells:
            c.rect(px, py, px + s - 1, py + s - 1, 0)
            c.rect(px, py + s - 1, px + s - 1, py + s - 1, 1)
    word("ORBIT", 14, 4)
    word("LANCE", 48, 4)
    planet(c, 80, 150, 30)
    return c

