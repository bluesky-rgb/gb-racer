# attract mode behind the title: a gentle loop, drawn with the title scene
TITLE = dict(name="TITLE", scene=3, song="SongTitle", time=99, bonus=0,
             segs=[(24, 0, -8), (26, 4, -8), (18, 0, -8), (26, -5, -8), (16, 0, -8), (22, 3, -8)],   # low horizon leaves room for the logo
             checkpoint=None, spacing=5, sign_every=4)

LAT_TREE = 11      # lateral position of scenery, eighths of the road half-width
LAT_SIGN = 12
LAT_POST = 9

out = ["; generated by tools/mktracks.py - do not edit", 'SECTION "Tracks", ROM0']

def emit(label, c):
    segs = c["segs"]
    total = sum(s[0] for s in segs)
    out.append(f"{label}Segs:")
    starts, pos = [], 0
    for i, (ln, curve, hill) in enumerate(segs):
        flags = 1 if c["checkpoint"] == i else 0
        out.append(f"    db {ln}, {curve}, {hill}, {flags}")
        starts.append(pos); pos += ln
    out.append(f"{label}SegsEnd:")
    # scenery: objects alternate sides; every few is the scene's second object, placed
    # on the outside of the bend; flag posts mark the start line and the checkpoint
    objs = []
    def seg_at(p):
        for i, s in enumerate(starts):
            if s <= p < s + segs[i][0]: return segs[i]
        return segs[-1]
    n, p = 0, 3
    while p < total - 1:
        curve = seg_at(p)[1]
        if n % c["sign_every"] == c["sign_every"] - 1:
            side = 1 if curve < 0 else 0 if curve > 0 else n & 1      # outside of the curve
            objs.append((p, 2 + side, LAT_SIGN))
        else:
            side = n & 1
            objs.append((p, 0 + side, LAT_TREE))
        n += 1
        p += c["spacing"]
    for cp in ([0] if c["checkpoint"] is None else [0, starts[c["checkpoint"]]]):
        q = cp if cp else total            # the start line is reached at the end of the lap
        q = min(q, total - 1) if cp == 0 else q
        objs.append((q, 4, LAT_POST)); objs.append((q, 5, LAT_POST))
    objs.sort()
    out.append(f"{label}Objs:")
    # entry: position, offset of the object's frame pointers, lateral - 1 (bit 7: right-hand side)
    for p, t, lat in objs: out.append(f"    dw {p}\n    db {t * 14}, {(lat - 1) | (0x80 if t & 1 else 0)}")
    out.append(f"{label}ObjsEnd:")
    out.append(f"{label}:: ; course header")
    out.append(f"    dw {label}Segs, {label}SegsEnd, {label}Objs, {label}ObjsEnd, {total}")
    out.append(f"    db {c['scene']}, {c['time']}, {c['bonus']}")
    out.append(f"    dw {c['song']}")
    out.append(f'    db "{c["name"]:<16}"')
    print(label, "length", total, "periods,", len(objs), "objects")

for i, c in enumerate(COURSES): emit(f"Course{i}", c)
emit("CourseTitle", TITLE)
out.append("CourseTable::\n    dw Course0, Course1, Course2, CourseTitle")
# rivals: distance ahead of the start line (periods), speed (8.8), lane, paint
RIVALS = [(5, 0x1500, -5, 0), (14, 0x1700, 4, 1), (26, 0x1900, 0, 0), (42, 0x1A80, -4, 1),
          (62, 0x1C00, 5, 0), (88, 0x1D80, -1, 1), (118, 0x1E80, 3, 0)]
out.append("RivalGrid::")
for d, sp, lat, paint in RIVALS:
    out.append(f"    db 0, 0\n    dw {d}, ${sp:04X}\n    db {lat}, {paint}")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
